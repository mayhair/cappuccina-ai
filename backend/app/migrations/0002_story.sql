-- Story mode: a chat's chosen scene and cast, the per-user switch for
-- suggested next actions, and the "story so far" chapter summaries.

ALTER TABLE chats ADD COLUMN story JSONB;

ALTER TABLE users ADD COLUMN story_choices BOOLEAN NOT NULL DEFAULT true;

-- One summary per section of a story's message path. start_uid/end_uid are the
-- first and last message uids it covers; a chapter only applies while end_uid
-- is on the branch being viewed. edited marks a summary the user rewrote, so
-- re-summarizing never overwrites it.
CREATE TABLE story_chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id TEXT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
    start_uid TEXT,
    end_uid TEXT,
    text TEXT NOT NULL,
    edited BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_story_chapters_chat ON story_chapters(chat_id, id);
